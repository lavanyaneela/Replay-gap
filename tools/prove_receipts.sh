# Deliberately corrupt the README five ways and show the number checker failing each time.
# A checker nobody has watched fail is a checker nobody should believe, so this is committed
# and its transcript is docs/receipts-proof.md.
#
# The README is restored after every case, including on an interrupt, so running this leaves
# the working tree exactly as it found it.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
WORK="$(mktemp -d)"
BACKUP="$WORK/README.backup"
OUT="$WORK/out.txt"
cp README.md "$BACKUP"
restore() { cp "$BACKUP" README.md; }
trap 'restore; rm -rf "$WORK"' EXIT INT TERM
run() { python3 tools/check_numbers.py --strict-reverse > "$OUT" 2>&1; echo $?; }

echo "# Proof that the number checker fails when it should"
echo
echo "A checker nobody has watched fail is a checker nobody should believe. This is the"
echo "transcript of ten deliberate corruptions, regenerated by tools/prove_receipts.sh, and"
echo "a test asserts that every case in it is a failure."
echo
echo "Cases 2 to 6 falsify a figure that is there. Cases 7, 8, 10 and 11 insert one that is"
echo "not, in a fence, in a code span and in image alt text, which is the attack the"
echo "mechanism missed until an audit went looking: guarding the lines that are there proves"
echo "those lines are current and says nothing about a line beside them. Case 9 is the"
echo "subtlest, and it is the one that forced the anchor rule to become per occurrence rather"
echo "than per document: a sentence that inverts the finding while quoting the right number,"
echo "sitting a hundred lines from the sentence that states it correctly."
echo
echo '```'
echo "=== 1. The repository as committed ==="
echo "exit $(run)"; grep -E "^checked|every published" "$OUT"

echo
echo "=== 2. One published figure moved by two hundredths of a point ==="
sed -i 's/+5\.53% better than itself/+5.51% better than itself/' README.md
echo "exit $(run)"; grep -E "STALE|UNGUARDED|stale figure|unguarded number" "$OUT" | head -4
restore

echo
echo "=== 3. Digits untouched, every sentence that framed them rewritten ==="
sed -i 's/+5\.53% better than itself/+5.53% uplift versus itself/' README.md
sed -i 's/own log reports +5\.53%/own log shows +5.53%/' README.md
echo "exit $(run)"; grep -E "STALE|UNGUARDED|stale figure" "$OUT" | head -4
restore

echo
echo "=== 4. One cell edited inside a guarded table row ==="
sed -i 's/| 50% | +9\.17% | +11\.81% | +9\.05% | 23,223 | 36 |/| 50% | +9.17% | +11.81% | +9.05% | 23,224 | 36 |/' README.md
echo "exit $(run)"; grep -E "STALE|UNGUARDED|stale figure" "$OUT" | head -4
restore

echo
echo "=== 5. A figure falsified inside a fenced block of captured output ==="
sed -i 's/^naive replay lift       +5\.53%   (on 17,187 matched sessions, 34\.4% of the log)$/naive replay lift       +9.99%   (on 42,000 matched sessions, 84.0% of the log)/' README.md
echo "exit $(run)"; grep -E "STALE|UNGUARDED|stale figure" "$OUT" | head -4
restore

echo
echo "=== 6. A number added that nothing measures ==="
sed -i 's/at 100% line coverage/at 100% line coverage and 61.4% branch coverage/' README.md
echo "exit $(run)"; grep -E "UNGUARDED|unguarded number" "$OUT" | head -3
restore

echo
echo "=== 7. A fabricated line inserted into the block of captured output ==="
python3 - <<'INSERT'
from pathlib import Path
p = Path("README.md")
p.write_text(
    p.read_text().replace(
        "effective sample size   50,000 of 50,000 (100.00%)\nlargest single weight",
        "effective sample size   50,000 of 50,000 (100.00%)\n"
        "precision at 5          99.4%   (best in class)\nlargest single weight",
    )
)
INSERT
echo "exit $(run)"; grep -E "fabricated|stale figure" "$OUT" | head -3
restore

echo
echo "=== 8. A figure hidden inside an inline code span ==="
sed -i 's/at 100% line coverage, one seed/at 100% line coverage and `61.4% branch coverage`, one seed/' README.md
echo "exit $(run)"; grep -E "fabricated|stale figure" "$OUT" | head -3
restore

echo
echo "=== 9. A false sentence placed beside a true one, both quoting the figure ==="
sed -i 's/it, and the same sweep ends at 1\.62%, below the floor, where the tool refuses\./it, and overlap stays comfortable throughout, never dropping under 1.62% of the log./' README.md
echo "exit $(run)"; grep -E "STALE|stale figure" "$OUT" | sed 's/, in \.\.\..*(anchors/ (anchors/' | head -2
restore

echo
echo "=== 10. A false claim inside a fence carrying no percent sign ==="
sed -i 's|fixtures/interactions/      the committed log|fixtures/interactions/      a 2,400,000 session log|' README.md
echo "exit $(run)"; grep -E "fabricated|stale figure" "$OUT" | head -2
restore

echo
echo "=== 11. A figure smuggled into image alt text ==="
sed -i 's|alt="The world, the log|alt="Naive replay overstates by 41.2% here. The world, the log|' README.md
echo "exit $(run)"; grep -E "fabricated|stale figure" "$OUT" | head -2
restore

echo
echo "=== 12. Restored ==="
echo "exit $(run)"; grep -E "^checked|every published" "$OUT"
echo '```'
